CeruleanCityRivalBattle:
	checkevent EVENT_BATTLED_CERULEAN_RIVAL
	iftrue .Done
	checkevent EVENT_BATTLED_RIVAL_IN_OAKS_LAB
	iffalse .Done
	disappear CERULEANCITY_RIVAL
	readvar VAR_XCOORD
	ifequal 21, .RightLane
	moveobject CERULEANCITY_RIVAL, 20, 2
	sjump .Approach
.RightLane:
	moveobject CERULEANCITY_RIVAL, 21, 2
.Approach:
; Reload this group's graphics before revealing BLUE, including connected entries.
	special RefreshSprites
	appear CERULEANCITY_RIVAL
	playmusic MUSIC_RIVAL_ENCOUNTER
	applymovement CERULEANCITY_RIVAL, CeruleanCityRivalApproach
	turnobject PLAYER, UP
	turnobject CERULEANCITY_RIVAL, DOWN
	opentext
	writetext CeruleanCityRivalChallengeText
	waitbutton
	closetext
	checkevent EVENT_GOT_BULBASAUR_FROM_OAK
	iftrue .Charmander
	checkevent EVENT_GOT_CHARMANDER_FROM_OAK
	iftrue .Squirtle
	loadtrainer PALLET_RIVAL, PALLET_RIVAL_CERULEAN_BULBASAUR
	sjump .Battle
.Charmander:
	loadtrainer PALLET_RIVAL, PALLET_RIVAL_CERULEAN_CHARMANDER
	sjump .Battle
.Squirtle:
	loadtrainer PALLET_RIVAL, PALLET_RIVAL_CERULEAN_SQUIRTLE
.Battle:
	winlosstext CeruleanCityRivalWinText, CeruleanCityRivalLossText
	setlasttalked CERULEANCITY_RIVAL
	startbattle
	reloadmapafterbattle
; A loss whites out before this point, so the encounter remains available.
	setevent EVENT_BATTLED_CERULEAN_RIVAL
	turnobject CERULEANCITY_RIVAL, DOWN
	opentext
	writetext CeruleanCityRivalLeavingText
	waitbutton
	closetext
	playmusic MUSIC_RIVAL_AFTER
	readvar VAR_XCOORD
	ifequal 21, .RightExit
	applymovement CERULEANCITY_RIVAL, CeruleanCityRivalExitLeftLane
	sjump .Leave
.RightExit:
	applymovement CERULEANCITY_RIVAL, CeruleanCityRivalExitRightLane
.Leave:
	disappear CERULEANCITY_RIVAL
	special RestartMapMusic
.Done:
	end

